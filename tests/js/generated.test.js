"use strict";
const test = require("node:test");
const assert = require("node:assert");
const { makeApp, item } = require("./app-harness");

const NOTE = { text: "A report <on> evidence & policy.", basis: "page-read", evidence: "https://x.example/", model: "claude-sonnet-5-5 (test)", generated_at: "2026-10-29T21:38:33Z" };

test("generated: an item with no generated note adds nothing to its card", () => {
  const h = makeApp({ items: [] });
  assert.equal(h.api.generated(item("a")), "");
  assert.equal(h.api.generated(item("a", { generated_note: null })), "");
  assert.ok(!h.api.card(item("a")).includes("generated by a language model"));
});

test("generated: a page-read note is labelled with model, date, time and basis, and is escaped", () => {
  const h = makeApp({ items: [] });
  const html = h.api.generated(item("a", { generated_note: NOTE }));
  assert.ok(html.startsWith('<details class="generated"><summary>Descriptive note generated by a language model</summary>'));
  assert.ok(html.includes("A report &lt;on&gt; evidence &amp; policy."));
  assert.ok(html.includes("claude-sonnet-5-5 (test), 2026-10-29 21:38:33 UTC, from the cited work's own page."));
  assert.ok(html.includes("Not part of the volume's annotation; it can contain errors."));
});

test("generated: a citation-only note says it rests on the citation alone", () => {
  const h = makeApp({ items: [] });
  const html = h.api.generated(item("a", { generated_note: Object.assign({}, NOTE, { basis: "citation-only" }) }));
  assert.ok(html.includes("from the citation alone."));
  assert.ok(!html.includes("own page"));
});

test("generated: the card shows the note after the 'no annotation' line for an unannotated item", () => {
  const h = makeApp({ items: [] });
  const card = h.api.card(item("a", { annotation: "", generated_note: NOTE }));
  const none = card.indexOf("No annotation in the source volume.");
  const note = card.indexOf("Descriptive note generated by a language model");
  assert.ok(none > 0 && note > none);
  assert.ok(card.indexOf('<ul class="tags"') > note);
});

test("crossref: a corrected item's card carries a labelled tag naming the fields", () => {
  const h = makeApp({ items: [] });
  const card = h.api.card(item("a", { crossref: { status: "corrected", fields: ["authors", "kind"] } }));
  assert.ok(card.includes('<li class="tag cr" title="Corrected from Crossref: authors, kind">Corrected from Crossref</li>'));
  assert.ok(card.indexOf("Corrected from Crossref</li>") < card.indexOf('<li class="tag vol">') + 1000);
});

test("crossref: other statuses, no check and an escaped field list add no tag or a safe one", () => {
  const h = makeApp({ items: [] });
  for (const status of ["matched", "not-registered", "different-work"]) {
    assert.ok(!h.api.card(item("a", { crossref: { status, fields: [] } })).includes("Corrected from Crossref"), status);
  }
  assert.ok(!h.api.card(item("a", { crossref: null })).includes("Corrected from Crossref"));
  assert.ok(!h.api.card(item("a")).includes("Corrected from Crossref"));
  const odd = h.api.card(item("a", { crossref: { status: "corrected", fields: ['a"b'] } }));
  assert.ok(odd.includes('title="Corrected from Crossref: a&quot;b"'));
});
